// Rebuild cropped bot assets from the existing masters without changing artwork.
// Uses sharp from the project or GAME_ASSET_NODE_MODULES; no runtime game dependency.
import { createRequire } from 'node:module';
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve, join } from 'node:path';
import { BOT_ENTRANCE_PROFILES } from '../frontend/src/game/bot-entrance.js';
import { BOT_PATHS } from '../frontend/src/game/sprites.js';

const require = createRequire(import.meta.url);
let sharp;
try { sharp = require('sharp'); } catch {
  if (!process.env.GAME_ASSET_NODE_MODULES) throw new Error('Set GAME_ASSET_NODE_MODULES to a folder containing sharp, then run node scripts/prepare-game-assets.mjs.');
  sharp = require(join(process.env.GAME_ASSET_NODE_MODULES, 'sharp'));
}
const root = fileURLToPath(new URL('../', import.meta.url));
const publicRoot = join(root, 'frontend/public');
const outputRoot = join(publicRoot, 'images/bots/optimized');
await mkdir(outputRoot, { recursive: true });
const manifest = {};
const sourceHashes = {};
for (const [type, sourcePath] of Object.entries(BOT_PATHS)) {
  const bytes = await readFile(resolve(publicRoot, '.' + sourcePath));
  sourceHashes[sourcePath] = createHash('sha256').update(bytes).digest('hex');
  const name = sourcePath.split('/').at(-1).replace(/\.png$/, '');
  const crops = [
    { role: 'gameplay', rect: [170, 130, 900, 1020], width: 256, height: 290 },
    { role: 'eyes', rect: BOT_ENTRANCE_PROFILES[type].crop, gutter: 2 },
  ];
  manifest[sourcePath] = [];
  for (const crop of crops) {
    const [left, top, width, height] = crop.rect;
    const gutter = crop.gutter || 0;
    // Preserve neighbouring pixels used by Canvas bilinear filtering at the
    // source-rectangle boundary, so eye crops render like the original master.
    let pipeline = sharp(bytes).extract({ left: left - gutter, top: top - gutter, width: width + gutter * 2, height: height + gutter * 2 });
    if (crop.width) pipeline = pipeline.resize(crop.width, crop.height, { fit: 'fill' });
    const { data, info } = await pipeline.png({ compressionLevel: 9 }).toBuffer({ resolveWithObject: true });
    const hash = createHash('sha256').update(data).digest('hex').slice(0, 12);
    const filename = `${name}-${crop.role}-${hash}.png`;
    await writeFile(join(outputRoot, filename), data);
    manifest[sourcePath].push({ path: `/images/bots/optimized/${filename}`, sourceRect: crop.rect,
      ...(gutter ? { drawRect: [gutter, gutter, width, height] } : {}), width: info.width, height: info.height });
  }
}
const file = join(root, 'frontend/src/game/bot-sprite-variants.js');
await writeFile(file, '// Generated by scripts/prepare-game-assets.mjs. Keep master paths/crops stable.\nexport const BOT_SPRITE_SOURCE_HASHES = ' + JSON.stringify(sourceHashes, null, 2) + ';\nexport const BOT_SPRITE_VARIANTS = ' + JSON.stringify(manifest, null, 2) + ';\n');
console.log('Generated 8 cropped bot variants and bot-sprite-variants.js (content-hashed URLs).');
